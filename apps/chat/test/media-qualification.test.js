import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PGlite} from '@electric-sql/pglite';
import {MediaQualification,mediaFingerprint} from '../src/features/media/qualification.js';
import {referenceImage} from '../src/features/media/probe-image.js';
import {eligibleMediaNode} from '../src/features/media/routing.js';
import {MediaQueue} from '../src/features/media/queue.js';
const image='qwen-image-fp8-832x480-v1';
test('isolated image qualification validates artifact, survives reload, gates profile and awards no credits',async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(`create table devices(node_id text primary key,public_key_hex text,agent_version text,backend text,contribution_percent int,worker_health_json jsonb,execution_history_json jsonb);
    create table jobs(assigned_node_id text,status text);
    create table media_generation_jobs(node_id text,state text,lease_until timestamptz);`);
  const migration=await readFile(new URL('../migrations/0047_media_qualification.sql',import.meta.url),'utf8');await db.exec(migration);await db.exec(migration);
  let clock=Date.now();const device={node_id:'probe-node',public_key_hex:'key',agent_version:'0.2.41',backend:'cuda',contribution_percent:80,
    worker_health_json:{runtime_mode:'media',media_budget_bytes:100*1024**3},execution_history_json:{qualification_required:true}};
  await db.query('insert into devices values($1,$2,$3,$4,$5,$6,$7)',Object.values(device));
  const store={pool:db,now:()=>clock,transaction:async fn=>{await db.exec('begin');try{const r=await fn(db);await db.exec('commit');return r;}catch(e){await db.exec('rollback');throw e;}}};
  const q=new MediaQualification(store,true);
  assert.deepEqual(await q.eligible(device,[image]),[]);
  const job=await q.claim(device,[image]);assert.equal(job.qualification,true);assert.equal(job.quote.compute_credits,0);
  assert.equal(await q.claim(device,[image]),null);
  const lease={job_id:job.job_id,lease_token:job.lease_token};
  await assert.rejects(q.reserve('other',lease),{statusCode:409});
  const bytes=referenceImage(),sha256=createHash('sha256').update(bytes).digest('hex');
  const ticket=await q.reserve(device.node_id,{...lease,metadata:{sha256,byte_size:bytes.length}});
  await assert.rejects(q.complete(device.node_id,{...lease,generation_ms:123}),{statusCode:409});
  await assert.rejects(q.upload(ticket.artifact_id,ticket.upload_ticket.upload_token,Buffer.alloc(bytes.length)),{statusCode:422});
  await q.upload(ticket.artifact_id,ticket.upload_ticket.upload_token,bytes);
  assert.equal((await q.complete(device.node_id,{...lease,generation_ms:123})).credits,0);
  assert.equal((await q.complete(device.node_id,{...lease,generation_ms:123})).qualification,true);
  assert.deepEqual(await new MediaQualification(store,true).eligible(device,[image]),[image]);
  assert.deepEqual(await q.eligible({...device,agent_version:'0.2.42'},[image]),[]);
  assert.equal((await db.query('select count(*)::int n from jobs')).rows[0].n,0);
  const live={...device,worker_health:device.worker_health_json,trust:{qualification_required:true},state:'ready',policy_allowed:true,updated_at:String(clock/1000)};
  live.worker_health={...live.worker_health,healthy:true,media_profiles:[image]};
  assert.equal(eligibleMediaNode(live,image,clock),false);
  live.media_qualifications=[{profile_id:image,state:'passed',fingerprint:mediaFingerprint(live,image)}];
  assert.equal(eligibleMediaNode(live,image,clock),true);
  live.media_qualifications[0].fingerprint='stale';assert.equal(eligibleMediaNode(live,image,clock),false);
  const queue=new MediaQueue(store,async()=>true);queue.qualification=q;
  clock+=1;const next=await q.claim(device,['wan22-i2v-lightning-14b-480p-49f-v3']);
  assert.equal(next.quote.operation,'image_to_video');
  const ref=await queue.input(device.node_id,{job_id:next.job_id,lease_token:next.lease_token});assert.equal(ref.sha256,sha256);
  clock+=180001;assert.equal(await q.claim(device,[next.profile_id]),null);
  assert.equal((await q.lookup(next.job_id)).state,'failed');
});
